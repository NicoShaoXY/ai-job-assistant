// 把用户自己的说话风格拼进系统提示词。
// 这是去 AI 味最有效的一招：给模型一个具体的模仿对象，比告诉它"写得自然一点"有用得多。
// 两个参数都可选：basePrompt 为空时用默认提示词，styleSamples 为空时行为完全不变。
export function buildGreetingSystemPrompt(styleSamples, basePrompt) {
  const base = String(basePrompt || "").trim() || GREETING_SYSTEM_PROMPT;
  const samples = String(styleSamples || "").trim();
  if (!samples) return base;
  return `${base}

─────

下面是这个人自己平时发消息的真实样子。请严格模仿他的语气、用词习惯和句子长短，不要照抄内容，只学语气：

${samples.slice(0, 1500)}`;
}

