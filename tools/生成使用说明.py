def style_run(run, size, bold=False, color=None):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def build() -> pathlib.Path:
    doc = Document()
    for name in ("Normal", "Heading 1", "List Bullet"):
        st = doc.styles[name]
        st.font.name = FONT
        st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)

    normal = doc.styles["Normal"]
    normal.font.size = Pt(10.5)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(4)

    for section in doc.sections:
        section.top_margin = Cm(2.2)
        section.bottom_margin = Cm(2.2)
        section.left_margin = Cm(2.4)
        section.right_margin = Cm(2.4)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    style_run(title.add_run("AI 求职助手"), 24, bold=True, color=INK)
    style_run(doc.add_paragraph().add_run(f"Chrome 侧边栏插件 · 使用说明 · {VERSION}"), 11, color=MUTED)
    style_run(doc.add_paragraph().add_run(f"作者 {AUTHOR}"), 11, color=MUTED)
    doc.add_paragraph()

    style_run(
        doc.add_paragraph().add_run(
            "在 BOSS 直聘的职位详情页一键读取 JD，算出你的简历和这个岗位的匹配度；结合简历生成打招呼语；"
            "HR 追问期望薪资时给出一条经得起追问的回复；投递前还能对这家公司做一次结构化的求职风险背调。"
        ),
        11,
    )

    for kind, text in SECTIONS:
        if kind == "h":
            heading = doc.add_heading(text, level=1)
            for run in heading.runs:
                style_run(run, 15, bold=True, color=INK)
        elif kind == "p":
            style_run(doc.add_paragraph().add_run(text), 10.5)
        elif kind == "b":
            style_run(doc.add_paragraph().add_run(text), 10.5, bold=True)
        elif kind == "w":
            style_run(doc.add_paragraph().add_run(text), 10.5, color=WARN)
        elif kind == "u":
            para = doc.add_paragraph(text, style="List Bullet")
            for run in para.runs:
                style_run(run, 10.5)
        elif kind == "s":
            para = doc.add_paragraph()
            para.paragraph_format.left_indent = Cm(0.6)
            style_run(para.add_run(text), 10)

    doc.add_paragraph()
    style_run(doc.add_paragraph().add_run(f"作者 {AUTHOR}"), 11, color=MUTED)

    target = pathlib.Path(__file__).parent.parent / "ai-job-assistant" / "使用说明.docx"
    doc.save(target)
    return target


if __name__ == "__main__":
    out = build()
    print(f"已生成 {out}（{out.stat().st_size} 字节）")
